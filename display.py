W, H = 128, 64

DEPARTURES = [
    ("2", "Theodor-Heuss-Platz", "2", "B"),
    ("10", "Donautal", "4", "A"),
    ("7", "Kasernstraße", "8", "B"),
    ("2", "Kuhberg", "8", "B"),
    ("2", "Theodor-Heuss-Platz", "12", "B"),
    ("5", "Wiley", "13", "B"),
    ("5", "Ludwigsfeld", "14", "B"),
]


def text_width(s):
    return sum(len(_G[c][0]) + 1 for c in s) - 1 if s else 0


def draw(img, s, x, y):
    for c in s:
        g = _G[c]
        for r, row in enumerate(g):
            for k, ch in enumerate(row):
                if ch == "#" and 0 <= y + r < H and 0 <= x + k < W:
                    img[y + r, x + k] = 1
        x += len(g[0]) + 1
    return x


def frame(rows=DEPARTURES, footer="Stadtgebiet: Aufgrund", clock="17:56"):
    img = np.zeros((H, W), np.uint8)
    for i, (line, dest, mins, plat) in enumerate(rows[:7]):
        y = i * 8
        draw(img, line, 10 - text_width(line), y)
        draw(img, dest, 13, y)
        draw(img, mins, 119 - text_width(mins) + 1, y)
        draw(img, plat, 123, y)
    draw(img, footer, 1, 56)
    draw(img, clock, W - text_width(clock), 56)
    return img


def texture(img, px=16, on=(1.0, 0.97, 0.9), off=0.035):
    """RGB float image (H*px, W*px, 3): round LEDs, faint unlit dots."""
    yy, xx = np.mgrid[0:px, 0:px] + 0.5
    d = np.hypot(xx - px / 2, yy - px / 2) / (px / 2)
    dot = np.clip((0.78 - d) / 0.18, 0, 1)  # soft-edged disc
    glow = np.exp(-(d**2) / 0.5) * 0.25
    lit = np.clip(dot + glow, 0, 1)
    out = np.zeros((H * px, W * px, 3), np.float32)
    big_on = np.kron(img, np.ones((px, px)))
    tile_lit = np.tile(lit, (H, W))
    tile_dot = np.tile(dot, (H, W))
    for ch in range(3):
        out[..., ch] = np.where(big_on > 0, tile_lit * on[ch], tile_dot * off)
    return out


